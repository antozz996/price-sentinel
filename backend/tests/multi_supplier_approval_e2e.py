ADMIN = SimpleNamespace(id=1, tenant_id=1)
SECOND_USER = SimpleNamespace(id=2, tenant_id=1)
SECOND_TENANT = SimpleNamespace(id=3, tenant_id=2)


def workbook_bytes(price: float | str = 2.5, count: int = 1, product_label: str = "Pomodori pelati") -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.append(["PRODOTTO", "UNITA DI MISURA", "MARR", "DAC"])
    for index in range(count):
        label = product_label if count == 1 else f"{product_label} {index+1}"
        ws.append([label, "Kg", price, 2.7])
    bio = BytesIO()
    wb.save(bio)
    return bio.getvalue()


def check(label: str, okay: bool) -> None:
    if not okay:
        raise AssertionError(label)
    print(f"PASS: {label}", flush=True)


async def call(payload: bytes, *, actor=ADMIN, dry_run=True, token=None, confirm=False):
    async with async_session_factory() as db:
        async with db.begin():
            return await import_multi_supplier(
                file=UploadFile(filename="listino-ci.xlsx", file=BytesIO(payload)),
                dry_run=dry_run,
                approval_token=token,
                confirm_import=confirm,
                _admin=actor,
                db=db,
            )


async def count(table: str) -> int:
    if table not in ("fornitori", "listino_master", "smart_price_sheet_previews"):
        raise AssertionError("unsafe table")
    async with async_session_factory() as db:
        return int((await db.execute(text(f"SELECT count(*) FROM {table}"))).scalar_one())


async def denied(label: str, awaitable, status: int = 403) -> None:
    try:
        await awaitable
    except HTTPException as exc:
        check(label, exc.status_code == status)
    else:
        raise AssertionError(label)


async def run() -> None:
    # Real preview metadata references the authenticated principal via FK.
    async with async_session_factory() as db:
        async with db.begin():
            await db.execute(text("""
                INSERT INTO utenti(id, email, password_hash, ruolo, tenant_id, attivo, refresh_token_version)
                VALUES
                    (1, 'comparative-admin-a@synthetic.test', 'x', 'admin', 1, true, 1),
                    (2, 'comparative-admin-b@synthetic.test', 'x', 'admin', 1, true, 1),
                    (3, 'comparative-admin-c@synthetic.test', 'x', 'admin', 2, true, 1)
            """))
    raw = workbook_bytes()
    alt = workbook_bytes(3.1)
    check("starts without suppliers or contracts", await count("fornitori") == 0 and await count("listino_master") == 0)

    # Five legacy mutation routes must fail BEFORE reading or writing to a DB.
    # All fixture identities and invoice prices are synthetic.
    async with async_session_factory() as db:
        prohibited = (
            ("unreviewed manual contract creation", create_listino(
                data=None, _admin=ADMIN, db=db,
            )),
            ("standard Excel writes without approval", import_listino_excel(
                fornitore_id=999, file=UploadFile(filename="listino-ci.xlsx", file=BytesIO(raw)),
                dry_run=False, _admin=ADMIN, db=db,
            )),
            ("unapproved invoiced price promotion", import_from_invoices_direct(
                fornitore_id=999, price_strategy="latest", _admin=ADMIN, db=db,
            )),
            ("permanent deletion of historic contract prices", delete_listino_fornitore(
                fornitore_id=999, _admin=ADMIN, db=db,
            )),
            ("unreviewed manual price update", aggiorna_prezzo_listino(
                listino_id=999, data=None, _admin=ADMIN, db=db,
            )),
        )
        for label, request in prohibited:
            await denied(label, request, 409)
    check("blocked legacy writes did not touch suppliers or contract history",
          await count("fornitori") == 0 and await count("listino_master") == 0)

    await denied("direct write without token prohibited", call(raw, dry_run=False, confirm=True))
    check("direct write denial performed no business writes", await count("fornitori") == 0 and await count("listino_master") == 0)

    # Invalid comparative offers must not even issue an approval token.
    # DAC remains valid in the fixture, so accepting a partial preview would be unsafe.
    for unsafe_value in ("-2,50", "2.12345", "circa 2,50"):
        rejected = await call(workbook_bytes(price=unsafe_value))
        check(
            f"unsafe supplier quote {unsafe_value!r} cannot produce an approval",
            rejected["mode"] == "validation_failed"
            and rejected["errors_count"] > 0
            and "preview_token" not in rejected,
        )
    check(
        "rejected Excel previews create no approval metadata or business rows",
        await count("smart_price_sheet_previews") == 0
        and await count("fornitori") == 0
        and await count("listino_master") == 0,
    )

    preview = await call(raw)
    check("preview returns signed token and rows", preview["mode"] == "dry_run"
          and preview["records_preview"][0]["prezzi"]["MARR"] == "2.5"
          and bool(preview["preview_token"]))
    check("preview persists control record only", await count("smart_price_sheet_previews") == 1
          and await count("fornitori") == 0 and await count("listino_master") == 0)
    token = preview["preview_token"]

    await denied("missing explicit human confirmation", call(raw, dry_run=False, token=token))
    await denied("changed uploaded file cannot consume token", call(alt, dry_run=False, token=token, confirm=True))
    await denied("other authenticated user cannot consume token", call(raw, actor=SECOND_USER, dry_run=False, token=token, confirm=True))
    await denied("different tenant cannot execute import", call(raw, actor=SECOND_TENANT, dry_run=False, token=token, confirm=True))
    await denied("invalid signature cannot execute import", call(raw, dry_run=False, token=token + "corrupt", confirm=True))
    check("all attempted bypasses remain side-effect-free", await count("fornitori") == 0 and await count("listino_master") == 0)

    bad_preview = await call(alt)
    signed = jwt.decode(bad_preview["preview_token"], settings.SECRET_KEY, algorithms=[settings.ALGORITHM])
    async with async_session_factory() as db:
        async with db.begin():
            await db.execute(
                text("UPDATE smart_price_sheet_previews SET expires_at=now()-interval '1 minute' WHERE id=cast(:id AS uuid)"),
                {"id": signed["jti"]},
            )
    await denied("expired stored approval cannot be used", call(alt, dry_run=False, token=bad_preview["preview_token"], confirm=True))

    # A single signed preview must be consumed by at most one concurrent worker.
    results = await asyncio.gather(
        call(raw, dry_run=False, token=token, confirm=True),
        call(raw, dry_run=False, token=token, confirm=True),
        return_exceptions=True,
    )
    successful = [r for r in results if isinstance(r, dict) and r.get("mode") == "imported"]
    refused = [r for r in results if isinstance(r, HTTPException) and r.status_code == 403]
    check("concurrent import replays serialized by row lock", len(successful) == 1 and len(refused) == 1)
    check("two suppliers and exactly two agreed prices were created",
          await count("fornitori") == 2 and await count("listino_master") == 2)
    async with async_session_factory() as db:
        result = (await db.execute(text("SELECT count(*) FROM fornitori WHERE attivo_whitelist=false"))).scalar_one()
    check("synthetic VAT suppliers are NOT approved for ordering", result == 2)

    await denied("spent preview token never accepted again", call(raw, dry_run=False, token=token, confirm=True))
    check("replay leaves price history untouched", await count("listino_master") == 2)

    latest = await call(raw)
    result = await call(raw, dry_run=False, token=latest["preview_token"], confirm=True)
    check("reimport skips identical prices", result["skipped_duplicates"] == 2 and result["inserted"] == 0 and result["updated"] == 0)
    check("identical reimport creates no duplicate contracts", await count("listino_master") == 2)

    # Different signed approvals are also serialized at the DB level.
    # Only one actual price update should occur for the changed MARR quotation.
    first_new, second_new = await call(alt), await call(alt)
    simultaneous = await asyncio.gather(
        call(alt, dry_run=False, token=first_new["preview_token"], confirm=True),
        call(alt, dry_run=False, token=second_new["preview_token"], confirm=True),
        return_exceptions=True,
    )
    successful = [result for result in simultaneous if isinstance(result, dict) and result.get("mode") == "imported"]
    stale_refusals = [result for result in simultaneous if isinstance(result, HTTPException) and result.status_code == 409]
    check("concurrent approvals allow one write and reject the now-stale comparison",
          len(successful) == 1 and successful[0]["updated"] == 1 and len(stale_refusals) == 1)
    check("only one historical version added and two active prices remain",
          await count("listino_master") == 3)
    async with async_session_factory() as db:
        active = (await db.execute(
            text("""SELECT count(*) FROM listino_master
               WHERE data_inizio_validita <= :today
                 AND (data_scadenza IS NULL OR data_scadenza >= :today)"""),
            {"today": datetime.now(ZoneInfo("Europe/Rome")).date()},
        )).scalar_one()
    check("single active record per supplier after concurrent approvals", active == 2)

    # Immutable date-only history: revisions approved today take effect tomorrow.
    today = datetime.now(ZoneInfo("Europe/Rome")).date()
    tomorrow = today + timedelta(days=1)
    async with async_session_factory() as db:
        marr_id = (await db.execute(text(
            "SELECT id FROM fornitori WHERE nome_azienda='MARR'"
        ))).scalar_one()
        versions = (await db.execute(text("""
            SELECT prezzo_pattuito, data_inizio_validita, data_scadenza
            FROM listino_master
            WHERE fornitore_id=:fid AND sku_interno='POMODORI-PELATI'
            ORDER BY data_inizio_validita ASC
        """), {"fid": marr_id})).all()
        check("revised agreement has old price through today and new price tomorrow",
              len(versions) == 2
              and float(versions[0][0]) == 2.5
              and versions[0][2] == today
              and float(versions[1][0]) == 3.1
              and versions[1][1] == tomorrow
              and versions[1][2] == tomorrow + timedelta(days=29))
        billed_today = await _get_listino_attivo(db, marr_id, "POMODORI-PELATI", today.isoformat())
        billed_tomorrow = await _get_listino_attivo(db, marr_id, "POMODORI-PELATI", tomorrow.isoformat())
        check("today's invoice uses old price; tomorrow uses new price for its 30-day term",
              billed_today is not None and float(billed_today.prezzo_pattuito) == 2.5
              and billed_tomorrow is not None and float(billed_tomorrow.prezzo_pattuito) == 3.1)
        expires_on = tomorrow + timedelta(days=29)
        billed_on_expiry = await _get_listino_attivo(
            db, marr_id, "POMODORI-PELATI", expires_on.isoformat()
        )
        billed_after_expiry = await _get_listino_attivo(
            db, marr_id, "POMODORI-PELATI", (expires_on + timedelta(days=1)).isoformat()
        )
        check("30-day contract covers its last day and expires the following day",
              billed_on_expiry is not None and float(billed_on_expiry.prezzo_pattuito) == 3.1
              and billed_after_expiry is None)
        currently_visible = await list_listino(
            response=Response(), fornitore_id=marr_id, include_scaduti=False,
            limit=50, offset=0, _user=ADMIN, db=db,
        )
        check("listino dashboard shows only today's price, not tomorrow's pending revision",
              len(currently_visible) == 1
              and float(currently_visible[0].prezzo_pattuito) == 2.5)
        check("malformed invoice date cannot silently select today's contract",
              await _get_listino_attivo(db, marr_id, "POMODORI-PELATI", "date-is-invalid") is None)

    # A conflicting second change must not replace tomorrow's already-approved version.
    changed_twice = workbook_bytes(4.2)
    change_preview = await call(changed_twice)
    check("conflicting future revision is blocked before token issuance",
          change_preview["mode"] == "validation_failed"
          and change_preview["errors_count"] > 0
          and not change_preview.get("preview_token"))
    check("conflicting future revisions do not add financial records",
          await count("listino_master") == 3)

    # Pre-existing overlapping history must never lead to an arbitrary invoice price.
    # Simulate ONLY inside an uncommitted transaction in the disposable CI database.
    async with async_session_factory() as db:
        db.add(ListinoMaster(
            fornitore_id=marr_id, sku_interno="POMODORI-PELATI",
            descrizione="Synthetic conflicting contract", prezzo_pattuito=4.9,
            unita_misura="Kg", data_inizio_validita=today,
            data_scadenza=today,
        ))
        await db.flush()
        check("ambiguous historical overlap refuses price selection",
              await _get_listino_attivo(db, marr_id, "POMODORI-PELATI", today) is None)
        await db.rollback()
    check("overlap simulation leaves persisted price history unchanged",
          await count("listino_master") == 3)

    full_preview = await call(workbook_bytes(count=60))
    check("all 60 Excel rows are visible for human approval",
          len(full_preview["records_preview"]) == 60
          and full_preview["records_preview_truncated"] is False)
    await denied("file above review cap is rejected before approval",
                 call(workbook_bytes(count=2001)), 413)
    check("large previews and invalid approvals leave business records untouched",
          await count("listino_master") == 3 and await count("fornitori") == 2)

    # An existing contract must be visible beside the proposed price and bind approval.
    async with async_session_factory() as db:
        async with db.begin():
            marr_id = (await db.execute(text(
                "SELECT id FROM fornitori WHERE nome_azienda='MARR'"
            ))).scalar_one()
            db.add(ListinoMaster(
                fornitore_id=marr_id, sku_interno="CACAO-AMARO",
                descrizione="Synthetic cacao contract", prezzo_pattuito=3.1,
                unita_misura="Kg", data_inizio_validita=today,
                data_scadenza=today + timedelta(days=29),
            ))
    approval_file = workbook_bytes(price=4.0, product_label="Cacao amaro")
    reviewed = await call(approval_file)
    marr_offer = next(
        offer for offer in reviewed["records_preview"][0]["confronti"]
        if offer["fornitore"] == "MARR"
    )
    check("preview shows current contract, proposed price, delta and 30-day dates",
          Decimal(marr_offer["prezzo_corrente"]) == Decimal("3.1")
          and Decimal(marr_offer["prezzo_proposto"]) == Decimal("4.0")
          and Decimal(marr_offer["delta_unitario"]) == Decimal("0.9")
          and marr_offer["decorrenza_proposta"] == today.isoformat()
          and marr_offer["scadenza_proposta"] == (today + timedelta(days=29)).isoformat())

    async with async_session_factory() as db:
        async with db.begin():
            await db.execute(text(
                "UPDATE listino_master SET prezzo_pattuito=3.2 WHERE sku_interno='CACAO-AMARO'"
            ))
    await denied("approval is rejected if contract changed after preview",
                 call(approval_file, dry_run=False, token=reviewed["preview_token"], confirm=True), 409)
    check("stale approval creates no contract rows", await count("listino_master") == 4)

    print("PASS: signed one-time comparative approval / replay / expiry / tenant / file digest E2E", flush=True)


if __name__ == "__main__":
    asyncio.run(run())
