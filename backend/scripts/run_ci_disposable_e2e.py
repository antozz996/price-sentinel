def gate_environment() -> str:
    if (
        os.environ.get("GITHUB_ACTIONS") != "true"
        or os.environ.get("RUNNER_ENVIRONMENT") != "github-hosted"
        or os.environ.get("CI") != "true"
    ):
        raise SystemExit("STOP: tests may run only on ephemeral GitHub-hosted CI runners")
    dsn = os.environ.get("CI_POSTGRES_ADMIN_DSN", "")
    try:
        u = make_url(dsn)
    except Exception as exc:
        raise SystemExit("STOP: invalid CI PostgreSQL URL") from exc
    if (
        u.drivername != "postgresql+psycopg2"
        or u.host != "127.0.0.1"
        or u.port != 5432
        or u.username != "ps_ci_runner"
        or u.database != "postgres"
        or not u.password
    ):
        raise SystemExit("STOP: CI PostgreSQL may connect only to loopback ephemeral runner")
    return dsn


async def create_tables(database_url: str) -> None:
    # Import only AFTER the test database environment is set.
    from app.database import Base, engine
    import app.models  # noqa: F401

    async with engine.begin() as connection:
        await connection.run_sync(Base.metadata.create_all)
    await engine.dispose()


def execute_case(name: str, admin_dsn: str) -> bool:
    from sqlalchemy.engine import make_url
    import psycopg2

    test_file, db_name, bootstrap_schema = CASES[name]
    if not db_name.startswith("ps_ci_disposable_"):
        raise SystemExit("STOP: non-disposable database name")

    # Unique DB per suite; CI postgres runs only for this workflow job.
    # psycopg2 expects a PostgreSQL URI, not SQLAlchemy's "+psycopg2" dialect URL.
    admin_uri = make_url(admin_dsn).set(drivername="postgresql").render_as_string(hide_password=False)
    # CREATE DATABASE must not run inside a transaction: psycopg2's
    # "with connection" context starts one even with autocommit enabled.
    connection = psycopg2.connect(admin_uri)
    try:
        connection.autocommit = True
        with connection.cursor() as cursor:
            cursor.execute("select 1 from pg_database where datname=%s", (db_name,))
            if cursor.fetchone():
                raise SystemExit("STOP: expected a brand-new disposable test DB")
            from psycopg2 import sql
            cursor.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(db_name)))
    finally:
        connection.close()

    original_url = make_url(admin_dsn)
    async_dsn = original_url.set(drivername="postgresql+asyncpg", database=db_name).render_as_string(hide_password=False)
    sync_dsn = original_url.set(drivername="postgresql", database=db_name).render_as_string(hide_password=False)
    env = dict(os.environ)
    env.update(
        {
            "DATABASE_URL": async_dsn,
            "TEST_DATABASE_DSN": sync_dsn,
            "ENVIRONMENT": "ci",
            "DEBUG": "false",
            "AUTOMATION_ENABLED": "false",
            "SECRET_KEY": secrets.token_urlsafe(48),
            "ARUBA_WEBHOOK_API_KEY": secrets.token_urlsafe(32),
            "LIQUIDSTOCK_INTEGRATION_SECRET": secrets.token_urlsafe(48),
            "GOD_MODE_TOKEN": "",
            "PYTHONPATH": str(Path(__file__).resolve().parents[1]),
        }
    )
    if bootstrap_schema:
        bootstrap = subprocess.run(
            [
                sys.executable,
                "-c",
                "import asyncio; from scripts.run_ci_disposable_e2e import create_tables; "
                "asyncio.run(create_tables(__import__('os').environ['DATABASE_URL']))",
            ],
            cwd=str(Path(__file__).resolve().parents[1]),
            env=env,
            check=False,
            timeout=120,
        )
        if bootstrap.returncode:
            print(f"FAIL: {name} — disposable schema bootstrap failed", flush=True)
            return False

    if name in ("onboarding_settings", "automation_alerts"):
        # Build known synthetic fixture through the existing audited E2E
        # scenario; it runs against the new case database, not shared staging.
        setup = subprocess.run(
            [sys.executable, str(Path(__file__).resolve().parents[1] / "tests" / "disputes_credit_notes_e2e.py")],
            cwd=str(Path(__file__).resolve().parents[1]),
            env=env,
            check=False,
            timeout=150,
        )
        if setup.returncode:
            print(f"FAIL: {name} — synthetic dispute fixture setup failed", flush=True)
            return False

    print(f"RUN: {name} against its independent CI-only disposable DB", flush=True)
    # LiquidStock inbound E2E talks to a temporary HTTP server on GitHub's
    # OWN 127.0.0.1 port; no external integration or Hetzner host is used.
    server = None
    if name == "liquidstock_inbound":
        import httpx
        import time
        env["INTEGRATION_TEST_DATABASE_DSN"] = sync_dsn
        env["INTEGRATION_TEST_BASE_URL"] = "http://127.0.0.1:18001"
        server = subprocess.Popen(
            [sys.executable, "-m", "uvicorn", "app.main:app",
             "--host", "127.0.0.1", "--port", "18001", "--no-access-log"],
            cwd=str(Path(__file__).resolve().parents[1]),
            env=env,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.STDOUT,
        )
    try:
        if server is not None:
            healthy = False
            for _ in range(60):
                if server.poll() is not None:
                    break
                try:
                    health = httpx.get("http://127.0.0.1:18001/api/v1/health", timeout=1.5)
                    if health.status_code == 200 and health.json().get("environment") == "ci":
                        healthy = True
                        break
                except httpx.RequestError:
                    pass
                time.sleep(0.25)
            if not healthy:
                print("FAIL: liquidstock_inbound — disposable loopback API did not start", flush=True)
                return False
        result = subprocess.run(
            [sys.executable, str(Path(__file__).resolve().parents[1] / "tests" / test_file)],
            cwd=str(Path(__file__).resolve().parents[1]),
            env=env,
            check=False,
            timeout=150,
        )
    except subprocess.TimeoutExpired:
        print(f"FAIL: {name} — timeout after 150 seconds", flush=True)
        return False
    finally:
        if server is not None:
            server.terminate()
            try:
                server.wait(timeout=5)
            except subprocess.TimeoutExpired:
                server.kill()
                server.wait(timeout=5)
    passed = result.returncode == 0
    print(f"{'PASS' if passed else 'FAIL'}: {name}", flush=True)
    return passed


def execute_v1_migration_rehearsal(admin_dsn: str) -> bool:
    """Prove the V1 Alembic head can upgrade to V2 and roll back in CI."""
    import psycopg2
    from psycopg2 import sql

    db_name = "ps_ci_disposable_v1_upgrade"
    admin_url = make_url(admin_dsn)
    admin_uri = admin_url.set(drivername="postgresql").render_as_string(hide_password=False)
    connection = psycopg2.connect(admin_uri)
    try:
        connection.autocommit = True
        with connection.cursor() as cursor:
            cursor.execute("select 1 from pg_database where datname=%s", (db_name,))
            if cursor.fetchone():
                raise SystemExit("STOP: expected a brand-new V1 migration rehearsal DB")
            cursor.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(db_name)))
    finally:
        connection.close()

    async_dsn = admin_url.set(
        drivername="postgresql+asyncpg", database=db_name
    ).render_as_string(hide_password=False)
    sync_dsn = admin_url.set(
        drivername="postgresql", database=db_name
    ).render_as_string(hide_password=False)
    env = dict(os.environ)
    env.update(
        {
            "DATABASE_URL": async_dsn,
            "ENVIRONMENT": "ci",
            "DEBUG": "false",
            "AUTOMATION_ENABLED": "false",
            "SECRET_KEY": secrets.token_urlsafe(48),
            "ARUBA_WEBHOOK_API_KEY": secrets.token_urlsafe(32),
            "LIQUIDSTOCK_INTEGRATION_SECRET": secrets.token_urlsafe(48),
            "GOD_MODE_TOKEN": "",
            "PYTHONPATH": str(Path(__file__).resolve().parents[1]),
        }
    )
    backend_root = str(Path(__file__).resolve().parents[1])

    # Reproduce the observed V1 production baseline without replaying every
    # historical migration from an empty database.  The legacy chain contains
    # old enum bootstrap assumptions that are unrelated to this release; the
    # real V1 database already has those tables and is stamped at this revision.
    bootstrap = subprocess.run(
        [
            sys.executable,
            "-c",
            "import asyncio; from scripts.run_ci_disposable_e2e import create_tables; "
            "asyncio.run(create_tables(__import__('os').environ['DATABASE_URL']))",
        ],
        cwd=backend_root,
        env=env,
        check=False,
        timeout=120,
    )
    if bootstrap.returncode:
        print("FAIL: V1 migration rehearsal schema bootstrap", flush=True)
        return False

    connection = psycopg2.connect(sync_dsn)
    try:
        with connection.cursor() as cursor:
            cursor.execute("drop table supplier_price_form_items")
            cursor.execute("drop table supplier_price_form_requests")
            cursor.execute("alter table supplier_product_aliases drop column brand")
            cursor.execute("alter table products alter column comparison_unit set not null")
            cursor.execute("alter table listino_master alter column unita_misura set not null")
        connection.commit()
    finally:
        connection.close()

    for command in (
        [sys.executable, "-m", "alembic", "stamp", "supplier_safe_archiving"],
        [sys.executable, "-m", "alembic", "upgrade", "head"],
    ):
        result = subprocess.run(
            command,
            cwd=backend_root,
            env=env,
            check=False,
            timeout=120,
        )
        if result.returncode:
            print("FAIL: V1-to-V2 migration rehearsal upgrade", flush=True)
            return False

    connection = psycopg2.connect(sync_dsn)
    try:
        with connection.cursor() as cursor:
            cursor.execute("select version_num from alembic_version")
            if cursor.fetchone() != ("supplier_multiple_offers",):
                print("FAIL: unexpected V2 Alembic head", flush=True)
                return False
            cursor.execute(
                """
                select count(*)
                from information_schema.columns
                where table_name = 'supplier_price_form_items'
                  and column_name in (
                    'brand_corrente', 'brand_inviata', 'dicitura_inviata',
                    'quantita_inviata', 'offerte_inviate'
                  )
                """
            )
            if cursor.fetchone() != (5,):
                print("FAIL: V2 supplier form columns missing", flush=True)
                return False
    finally:
        connection.close()

    rollback = subprocess.run(
        [sys.executable, "-m", "alembic", "downgrade", "supplier_safe_archiving"],
        cwd=backend_root,
        env=env,
        check=False,
        timeout=120,
    )
    if rollback.returncode:
        print("FAIL: V2-to-V1 migration rehearsal rollback", flush=True)
        return False

    connection = psycopg2.connect(sync_dsn)
    try:
        with connection.cursor() as cursor:
            cursor.execute("select version_num from alembic_version")
            if cursor.fetchone() != ("supplier_safe_archiving",):
                print("FAIL: rollback did not restore V1 Alembic revision", flush=True)
                return False
            cursor.execute("select to_regclass('public.supplier_price_form_items')")
            if cursor.fetchone() != (None,):
                print("FAIL: rollback left a V2-only table in the V1 schema", flush=True)
                return False
    finally:
        connection.close()

    print("PASS: V1 schema upgrades to V2 and rolls back on disposable PostgreSQL", flush=True)
    return True


def main() -> None:
    if sys.argv[1:] != ["--github-ephemeral-only"]:
        raise SystemExit("STOP: explicit --github-ephemeral-only required")
    dsn = gate_environment()
    print("PASS: GitHub-hosted disposable Postgres isolation guard", flush=True)
    failures: list[str] = []
    if not execute_v1_migration_rehearsal(dsn):
        failures.append("v1_migration_rehearsal")
    for name in CASES:
        if not execute_case(name, dsn):
            failures.append(name)
    if failures:
        raise SystemExit("FAIL: isolated E2E suites: " + ", ".join(failures))
    print(f"PASS: {len(CASES)} isolated database E2E suites completed", flush=True)


if __name__ == "__main__":
    main()
